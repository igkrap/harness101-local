import assert from 'node:assert/strict';
import { deriveFlow } from '../web/src/flowState.ts';

const event = (type, data = {}, seq = 1) => ({type, data, seq, time:'2026-10-31T14:00:00Z'});
const events = (...items) => items.map(([type, data], i) => event(type, data, i+1));
const job = (status='running', kind='agent') => ({id:'fixture', kind, status, goal:'테스트 작업'});
const start = [['run.started'], ['check.started'], ['check.finished', {success:false}]];
assert.equal(deriveFlow([], undefined).current, null);
let flow = deriveFlow(events(...start, ['model.request']), job());
assert.equal(flow.current, 'plan');
assert.equal(flow.records.baseline.at(-1).data.success, false);
flow = deriveFlow(events(...start, ['model.request'], ['autonomy.plan'], ['model.request'], ['tool.started'], ['tool.finished'], ['model.request']), job());
assert.equal(flow.current, 'model');
assert.equal(flow.records.check.length, 0, 'read-only tool must not imply a post-edit check');
assert(flow.edges.has('tool:model'));
const failed = events(...start, ['autonomy.plan'], ['model.request'], ['tool.started'], ['check.started'], ['check.finished',{success:false}], ['autonomy.rollback',{paths:['app.py']}], ['autonomy.retry'], ['model.request']);
flow = deriveFlow(failed, job());
assert.equal(flow.current, 'model');
assert(flow.edges.has('check:rollback'));assert(flow.edges.has('rollback:retry'));assert(flow.edges.has('retry:model'));
flow = deriveFlow(events(...start, ['autonomy.plan'], ['model.request'], ['autonomy.blocked',{error:'not allowed'}], ['autonomy.retry']), job());
assert.equal(flow.current, 'retry');assert.equal(flow.records.rollback.length, 0, 'blocked edit is not a rollback');
flow = deriveFlow(events(['run.started'], ['check.started'], ['check.finished',{success:true}], ['run.finished',{success:true}]), job('succeeded','checks'));
assert.equal(flow.current, 'finish');assert.equal(flow.checksOnly, true);assert.equal(flow.records.model.length,0);assert.equal(flow.records.check.length,0);
flow = deriveFlow(failed, job('stopped'));
assert.equal(flow.current, 'finish');assert.equal(flow.status, 'stopped');assert.equal(flow.records.finish.length,0);
flow = deriveFlow(events(['run.finished',{success:true}]), job('stopped'));
assert.equal(flow.status,'stopped', 'owned process terminal status must take precedence');
flow = deriveFlow(events(['run.finished',{success:false}]), job('running'));
assert.equal(flow.ended,true);assert.equal(flow.status,'failed');
flow = deriveFlow([event('check.finished',{success:true},501)],job());
assert.equal(flow.incomplete,true);assert.equal(flow.records.check.length,1);assert.equal(flow.records.baseline.length,0);
console.log('FLOW_STATE_OK: planning, read loop, rollback, blocked edit, checks-only, stop, terminal race, truncated history');
