import copy
import pathlib
import sys
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from spec_workshop.contracts import validate, digest, ddl
from spec_workshop.demo import definition


class DevelopmentSpecificationTests(unittest.TestCase):
    def test_operation_requiredness_is_distinct_from_query_visibility_and_write_inputs(self):
        bundle = validate(definition())
        query = bundle['operations']['query']['inputs']
        self.assertTrue(query[0]['required'])
        self.assertFalse(query[1]['required'])
        self.assertEqual(query[2]['section'], 'advanced')
        self.assertNotIn('id', [field['name'] for field in bundle['operations']['create']['inputs']])
        self.assertEqual(digest(bundle), digest(copy.deepcopy(bundle)))

    def test_missing_or_ambiguous_contracts_fail_before_generation(self):
        mutations = [
            lambda b: b['operations'].pop('update'),
            lambda b: b['operations']['query']['inputs'][0].pop('required'),
            lambda b: b['operations']['create']['inputs'].append({'name':'id','field':'id','required':True}),
            lambda b: b['operations']['update'].update(transaction='guess'),
            lambda b: b['screen'].update(code='AB0001'),
            lambda b: b['entity']['fields'].append(b['entity']['fields'][1]),
            lambda b: b['operations']['query']['inputs'][0].update(field='missing'),
            lambda b: b['entity'].update(table='users; DROP TABLE inventory'),
            lambda b: b['screen'].update(pattern='free'),
        ]
        for mutate in mutations:
            with self.subTest(mutation=mutate):
                bundle = definition(); mutate(bundle)
                with self.assertRaises(ValueError): validate(bundle)

    def test_ddl_has_server_generated_fields_and_database_constraints(self):
        sql = ddl(definition())
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', sql)
        self.assertIn('DEFAULT now()', sql)
        self.assertIn('CHECK ("quota" >= 0)', sql)
        self.assertNotIn('INSERT', sql)
